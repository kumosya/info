/* PIT IRQ0 stub: call C handler and iretq */
pit_stub:
    cli

    push %rax
    movq %es, %rax
    push %rax
    movq %ds, %rax
    push %rax
    push %rbx
    push %rcx
    push %rdx
    push %rsi
    push %rdi
    push %rbp
    push %r8
    push %r9
    push %r10
    push %r11
    push %r12
    push %r13
    push %r14
    push %r15

    /*
     * 进入时：
     *  - 若来自用户态：GS = 用户 GS
     *  - 若来自内核态：GS = 内核 GS
     */

    /* Check CPL (CS.RPL) to see if we came from user (CPL==3). */
    testl $3, CS(%rsp)        # CS.RPL & 3 == CPL
    je .from_kernel
    swapgs                   # 切换到内核 GS
.from_kernel:
    /* 现在开始，GS 一定是内核 GS */
    
    call pit_handler_c

    /* 
     * 返回前：
     * 必须与入口完全对称
     * 判断依据仍然是“最初的 CS”
     */
    testl $3, CS(%rsp)        # CS.RPL & 3 == CPL
    je .return_to_kernel
    swapgs                   # 内核 → 用户
.return_to_kernel:

    pop %r15
    pop %r14
    pop %r13
    pop %r12
    pop %r11
    pop %r10
    pop %r9
    pop %r8
    pop %rbp
    pop %rdi
    pop %rsi
    pop %rdx
    pop %rcx
    pop %rbx
    pop %rax
    movq %rax, %ds
    pop %rax
    movq %rax, %es
    pop %rax

    sti
    iretq


/* Keyboard IRQ1 stub */

kbd_stub:
    cli
    push %rax
    movq %ds, %rax
    push %rax
    movq %ds, %rax
    push %rax
    push %rbx
    push %rcx
    push %rdx
    push %rsi
    push %rdi
    push %rbp
    push %r8
    push %r9
    push %r10
    push %r11
    push %r12
    push %r13
    push %r14
    push %r15

    /* If we came from user mode, swapgs to get kernel GS before
       touching per-cpu data or kernel-side stacks. */
    testl $3, CS(%rsp)        # CS.RPL & 3 == CPL
    je .kbd_from_kernel
    swapgs
.kbd_from_kernel:

    call kbd_handler_c 

    /* Swap back to user GS if necessary. */
    testl $3, CS(%rsp)        # CS.RPL & 3 == CPL
    je .kbd_return_to_kernel
    swapgs
.kbd_return_to_kernel:
    pop %r15
    pop %r14
    pop %r13
    pop %r12
    pop %r11
    pop %r10
    pop %r9
    pop %r8
    pop %rbp
    pop %rdi
    pop %rsi
    pop %rdx
    pop %rcx
    pop %rbx
    pop %rax
    movq %rax, %ds
    pop %rax
    movq %rax, %es
    pop %rax
    sti
    iretq


